export function halloweenOn(now: number): boolean {
  return now < new Date(HALLOWEEN.ends).getTime();
}

/** 預設打開哪一章：已經開放的最新那一章 */
export function halloweenChapterFor(now: number): 1 | 2 | 3 {
  let latest: 1 | 2 | 3 = 1;
  for (const chapter of HALLOWEEN.chapters) if (now >= new Date(chapter.opens).getTime()) latest = chapter.no;
  return latest;
}
